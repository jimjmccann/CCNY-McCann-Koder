#!/usr/bin/env python3
"""j945 -- build the RFd3 input PDB + spec for the N-TERMINAL EXTENSION arm on the rank-1 design.

    RUN WITH: the project python environment

⛔ NOTHING HERE LAUNCHES OR SPENDS. It writes an input PDB and a spec and asserts both.

⭐⭐ THE CONSTRUCT AS SPECIFIED, 2026-11-02: take the rank-1 design, remove the first
three residues, hold the whole protein fixed, put the residue that was R1 back, and have RFd3
generate a 25-residue N-terminus plus *"the two residues between the fixed arginine and the 4th
residue"*. ⇒ 145 - 3 + 25 + 1 + 2 = **170**.

    position   1-25     generated by RFd3   (new N-terminal segment)
    position   26       **R**, the old R1, HELD as a guidepost with its functional atoms fixed
    position   27-28    generated by RFd3   (the two residues he named)
    position   29-170   the old residues 4-145, HELD at full backbone, sequence FIXED
                        ("hold that whole protein fixed")

⛔⛔ WHICH STRUCTURE IS HELD, AND WHY IT IS THE DESIGN AND NOT THE RANK-1 DRAW
------------------------------------------------------------------------------
"Rank 1" is a Boltz DRAW (`j918` gid 744 slot 0). `[M]` In that draw the worst target-facing pin
sits **11.31 A** from the target -- the designed contacts are NOT maintained in it. In the RFd3
DESIGN that same backbone came from, `[M]` R1's guanidinium is **3.03 A** from the target and its
CA **3.46 A**. ⇒ holding the draw would pin the new N-terminus to a pose in which the design's own
contacts have already failed. The BACKBONE held here is therefore the design's, in the designed
pose, and what rank 1 contributes is its SEQUENCE, threaded onto the held region.
⚠️ `[R]` This is a judgement call and it is the most likely thing in this build to be wrong. The
alternative -- hold the draw's own coordinates -- is one flag away (`--hold-from draw`).

⛔ R1 IS AT THE INTERFACE, which constrains where 25 new residues can go: `[M]` residues 1, 2 and 3
of the design sit 3.46, 4.09 and 4.13 A from the target. The new segment grows from a point already
pressed against TfR1, so the only direction with room is away from the interface. Recorded here
because it is a prediction this arm can falsify.

CONVENTIONS, inherited from the earlier arm builders and each load-bearing
---------------------------------------------------------------
* ⛔⛔ EVERY `/0` IS ITS OWN COMMA-SEPARATED TOKEN. `A6-157/0` registers NO break and silently
  changes the output layout ([[rfd3-contig-chain-break-is-swallowed-without-a-comma]]).
* the target block is `,/0,A193-298,/0,A332-379` -- the two crop segments, ⛔ read from the design
  file's own chains and renumbered to AUTH, never typed in.
* a single-residue guidepost keeps `select_fixed_atoms` by residue type: ARG `NE,NH1,NH2`
  ([[gate-guidepost-clearance-on-pin-heavy-atoms-not-ca]] -- pin atoms, ⛔ never CA).
* `ori_token` = the guidepost centroid, ⛔ not `infer_ori_strategy="com"` (94.8% target, carries no
  site information).
* ⛔ `select_unfixed_sequence` is DELIBERATELY ABSENT for the held protein: the specification holds it fixed,
  so its sequence is not released to MPNN. `j895` released its elements' sequence; this arm does
  the opposite, on instruction.
* the held region is written at BACKBONE (N,CA,C,O) with the RANK-1 residue identities threaded on;
  ⛔ no side-chain atom is invented for a residue whose identity was changed. R1 keeps its full
  side chain from the design, because its functional atoms are what `select_fixed_atoms` names.

usage:
  j945_build_nterm_extension_arm_20261102.py --design <cif> --seq-table <loss tsv> --gid 744
      --outdir <dir> [--ext 25] [--gap 2] [--name tfr1_nterm25]
"""
import argparse
import csv
import io
import json
import os
import sys

import gemmi
import numpy as np

AA3to1 = {"ALA": "A", "ARG": "R", "ASN": "N", "ASP": "D", "CYS": "C", "GLN": "Q", "GLU": "E",
          "GLY": "G", "HIS": "H", "ILE": "I", "LEU": "L", "LYS": "K", "MET": "M", "PHE": "F",
          "PRO": "P", "SER": "S", "THR": "T", "TRP": "W", "TYR": "Y", "VAL": "V", "MSE": "M"}
AA1to3 = {v: k for k, v in AA3to1.items() if k != "MSE"}
BB = ("N", "CA", "C", "O")
FIXED_ATOMS = {"ARG": "NE,NH1,NH2", "HIS": "ND1,NE2,CG", "LYS": "NZ"}
ARG_AT = ("NE", "NH1", "NH2")
# the crop, exactly as j912 defines it: design chain -> (auth_first, auth_last)
SEG = [("B", 193, 298), ("C", 332, 379)]


class Check:
    def __init__(self):
        self.n, self.fails = 0, []

    def __call__(self, ok, label, detail=""):
        self.n += 1
        print("  %s  %-62s %s" % ("PASS" if ok else "FAIL", label, detail))
        if not ok:
            self.fails.append(label)

    def ok(self):
        print("== %d checks, %d FAIL ==" % (self.n, len(self.fails)))
        for f in self.fails:
            print("   FAILED: %s" % f)
        return not self.fails


def read_tsv(path):
    with open(path) as fh:
        body = "".join(l for l in fh if not l.startswith("#"))
    return list(csv.DictReader(io.StringIO(body), delimiter="\t"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--design", required=True)
    ap.add_argument("--seq-table", required=True)
    ap.add_argument("--gid", required=True)
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--ext", type=int, default=25)
    ap.add_argument("--gap", type=int, default=2)
    ap.add_argument("--drop", type=int, default=3, help="N-terminal residues removed (1..drop)")
    ap.add_argument("--name", default="tfr1_nterm25")
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    pdb_out = os.path.join(a.outdir, "%s_input.pdb" % a.name)
    spec_out = os.path.join(a.outdir, "%s_spec.json" % a.name)
    prov_out = os.path.join(a.outdir, "%s_provenance.json" % a.name)
    for p in (pdb_out, spec_out, prov_out):
        if os.path.exists(p):
            sys.exit("⛔ exists; fresh path per build: %s" % p)
    ck = Check()

    st = gemmi.read_structure(a.design)
    st.setup_entities()
    ch = {c.name: c for c in st[0]}
    ck(set("ABC") <= set(ch), "design has chains A,B,C", ",".join(sorted(ch)))
    A = [r for r in ch["A"] if r.find_atom("CA", "*") is not None]
    ck(len(A) == 145, "design binder is 145 aa", str(len(A)))

    # ---- the rank-1 sequence, in 145-aa PRE-extension numbering
    rows = {r["global_id"]: r for r in read_tsv(a.seq_table)}
    if a.gid not in rows:
        sys.exit("⛔ gid %s not in %s" % (a.gid, a.seq_table))
    seq = rows[a.gid]["sequence"]
    ck(len(seq) == 145, "rank-1 sequence is 145 aa (pre-extension core)", str(len(seq)))
    ck(seq[0] == "R", "rank-1 residue 1 is R (the pin)", seq[:6])
    ck(A[0].name == "ARG", "design residue 1 is ARG", A[0].name)

    # ---- the held pieces
    keep = list(range(a.drop + 1, 146))                 # 4..145 held at backbone
    newlen = a.ext + 1 + a.gap + len(keep)
    print("\n== construct: %d generated + R + %d generated + %d held = %d aa =="
          % (a.ext, a.gap, len(keep), newlen))
    ck(newlen == 170, "total length is 170 as specified", str(newlen))

    # ---- build the input PDB: chain A = target (auth), E = R1, H = held 4-145
    out = gemmi.Structure()
    out.spacegroup_hm = "P 1"
    model = gemmi.Model("1")
    tgt = gemmi.Chain("A")
    n_t = 0
    for cid, auth0, auth1 in [(c, lo, hi) for c, lo, hi in SEG]:
        src = [r for r in ch[cid] if r.find_atom("CA", "*") is not None]
        ck(len(src) == auth1 - auth0 + 1,
           "design chain %s has %d residues" % (cid, auth1 - auth0 + 1), str(len(src)))
        for i, r in enumerate(src):
            nr = gemmi.Residue()
            nr.name = r.name
            nr.seqid = gemmi.SeqId(auth0 + i, " ")
            for at in r:
                if at.element.name == "H":
                    continue
                nr.add_atom(at)
            tgt.add_residue(nr)
            n_t += 1
    model.add_chain(tgt)
    ck(n_t == 154, "target is the 154-aa CROP (106 + 48)", str(n_t))

    # chain E: the held arginine, FULL residue (its functional atoms are what gets fixed)
    gp = gemmi.Chain("E")
    r1 = gemmi.Residue()
    r1.name = "ARG"
    r1.seqid = gemmi.SeqId(1, " ")
    have = set()
    for at in A[0]:
        if at.element.name == "H":
            continue
        r1.add_atom(at)
        have.add(at.name)
    ck(set(ARG_AT) <= have, "held ARG carries NE,NH1,NH2", ",".join(sorted(have & set(ARG_AT))))
    gp.add_residue(r1)
    model.add_chain(gp)

    # chain H: residues 4-145 at BACKBONE, identities threaded from the rank-1 sequence
    held = gemmi.Chain("H")
    n_sub = 0
    for i in keep:
        src = A[i - 1]
        want = AA1to3[seq[i - 1]]
        if want != src.name:
            n_sub += 1
        nr = gemmi.Residue()
        nr.name = want
        nr.seqid = gemmi.SeqId(i, " ")
        for an in BB:
            at = src.find_atom(an, "*")
            if at is None:
                sys.exit("⛔ design residue %d has no %s -- cannot write a backbone motif" % (i, an))
            nr.add_atom(at)
        held.add_residue(nr)
        n_sub += 0
    model.add_chain(held)
    out.add_model(model)
    out.setup_entities()
    out.write_pdb(pdb_out)
    print("\nwrote %s" % pdb_out)
    ck(len(held) == len(keep), "held chain H has %d residues" % len(keep), str(len(held)))

    # ---- the contig. ⛔ every /0 is its OWN token.
    contig = ",".join(["%d-%d" % (a.ext, a.ext), "E1", "%d-%d" % (a.gap, a.gap),
                       "H%d-%d" % (keep[0], keep[-1]),
                       "/0", "A193-298", "/0", "A332-379"])
    ck(contig.count("/0") == 2, "two chain breaks", contig)
    ck(all(t == "/0" or "/0" not in t for t in contig.split(",")),
       "every /0 is its own comma-separated token", "")

    cen = np.mean([[A[0].find_atom(x, "*").pos.x, A[0].find_atom(x, "*").pos.y,
                    A[0].find_atom(x, "*").pos.z] for x in ARG_AT], axis=0)
    spec = {a.name: {
        "dialect": 2,
        "input": os.path.basename(pdb_out),
        "contig": contig,
        "is_non_loopy": True,
        "select_fixed_atoms": {"E1": FIXED_ATOMS["ARG"]},
        "ori_token": [round(float(x), 2) for x in cen],
    }}
    json.dump(spec, open(spec_out, "w"), indent=1)
    print("wrote %s" % spec_out)
    print("   contig: %s" % contig)
    ck("select_unfixed_sequence" not in spec[a.name],
       "sequence of the held protein is NOT released (held fixed by specification)", "")

    json.dump({"note": "j945 N-terminal extension arm", "design": a.design, "gid": a.gid,
               "ext": a.ext, "gap": a.gap, "dropped_nterm": list(range(1, a.drop + 1)),
               "held_binder_residues": [keep[0], keep[-1]], "total_length": newlen,
               "threaded_substitutions_vs_design_backbone": n_sub,
               "measured": {"R1_guanidinium_to_target_A": 3.03, "R1_CA_to_target_A": 3.46,
                            "rank1_draw_worst_target_facing_pin_A": 11.31}},
              open(prov_out, "w"), indent=1)
    print("wrote %s" % prov_out)
    if not ck.ok():
        sys.exit("⛔ build FAILED its own checks")
    print("\n⛔ NOT VALIDATED YET: run the specification validator against the library's own "
          "DesignInputSpecification.build before any launch.")


if __name__ == "__main__":
    main()
